# ─────────────────────────────────────────────────────────────────────────────
# Ajustes para decidir cuándo una tabla debe ir en una página horizontal.
# Se pueden afinar sin tocar el resto del código.
# ─────────────────────────────────────────────────────────────────────────────
PORTRAIT_WIDTH_PX      = 640    # ancho útil aprox. de una página A4 vertical (px CSS)
CHAR_PX                = 8.0    # ancho medio estimado de un carácter
CELL_PAD_PX            = 32     # padding horizontal total por columna (1rem + 1rem)
NATURAL_CAP_CHARS      = 32     # una celda "natural" no pasa de este nº de caracteres
NATURAL_OVERFLOW_RATIO = 1.35   # tolerancia antes de pasar a horizontal
LANDSCAPE_MIN_COLS     = 7      # 7 o más columnas → siempre horizontal

_TABLE_RE = re.compile(r'<table\b[^>]*>.*?</table>', re.DOTALL | re.IGNORECASE)
_ROW_RE   = re.compile(r'<tr\b[^>]*>(.*?)</tr>', re.DOTALL | re.IGNORECASE)
_CELL_RE  = re.compile(r'<t[hd]\b[^>]*>(.*?)</t[hd]>', re.DOTALL | re.IGNORECASE)
_TAG_RE   = re.compile(r'<[^>]+>')
# Fila separadora de tabla markdown con cualquier nº de columnas: | --- | :---: | ---: |
_SEP_RE   = re.compile(r'^\s*\|?\s*:?-+:?\s*(\|\s*:?-+:?\s*)*\|?\s*$')
# Encabezado (+ párrafo opcional) que está justo antes de una tabla:
# se mueve junto con la tabla a la página horizontal para no quedar huérfano.
_LEAD_RE  = re.compile(
    r'<h[1-6][^>]*>(?:(?!</h[1-6]>).)*</h[1-6]>\s*'
    r'(?:<p[^>]*>(?:(?!</p>).)*</p>\s*)?$',
    re.DOTALL | re.IGNORECASE,
)
_EMOJI_RE = re.compile('[\U0001F000-\U0001FFFF\u2600-\u27BF\u2B00-\u2BFF\uFE0F\u200d]')
_NATIVE_DLL_HANDLES = []
_NATIVE_DLL_DIRECTORIES = set()
_WEASYPRINT_CHECKED = False   # se evalúa una sola vez por proceso
_WEASYPRINT_OK = False        # resultado de la comprobación


def _weasyprint_available() -> bool:
    """
    Comprueba de forma segura (sin crashear el proceso) si WeasyPrint
    puede importarse y tiene las dependencias nativas necesarias.
    El resultado se cachea para no repetir la comprobación.
    En Windows, verifica la existencia de DLLs de Pango antes de intentar
    el import, ya que un import fallido puede matar el proceso con un
    error nativo de C en lugar de levantar una excepción Python normal.
    """
    global _WEASYPRINT_CHECKED, _WEASYPRINT_OK
    if _WEASYPRINT_CHECKED:
        return _WEASYPRINT_OK

    _WEASYPRINT_CHECKED = True

    # En Windows: comprobamos si las DLLs de Pango existen ANTES de importar.
    # Rutas candidatas idénticas a las de _configure_native_libraries().
    if os.name == 'nt':
        project_root = Path(__file__).resolve().parents[1]
        candidate_dirs = [
            Path('C:/msys64/ucrt64/bin'),
            Path('C:/msys64/mingw64/bin'),
            Path('C:/msys64/clang64/bin'),
            project_root / '.native' / 'msys64' / 'ucrt64' / 'bin',
            project_root / '.native' / 'msys64' / 'mingw64' / 'bin',
            project_root / '.native' / 'bin',
            Path('C:/Program Files/GTK3-Runtime Win64/bin'),
            Path('C:/Program Files (x86)/GTK3-Runtime Win64/bin'),
        ]
        custom = os.environ.get('WEASYPRINT_DLL_DIRECTORIES') or os.environ.get('GTK_BASEPATH')
        if custom:
            for d in custom.split(os.pathsep):
                if d.strip():
                    candidate_dirs.insert(0, Path(d.strip()))

        pango_found = any(
            d.exists() and d.is_dir() and any(d.glob('*pango*.dll'))
            for d in candidate_dirs
        )
        if not pango_found:
            print("[PDF] WeasyPrint no disponible en Windows: DLLs de Pango no encontradas. Usando ReportLab.")
            _WEASYPRINT_OK = False
            return False

    # Verificamos el import en un subproceso aislado — si WeasyPrint crashea
    # el proceso, solo muere el subproceso y Flask sigue funcionando.
    import subprocess
    import sys
    try:
        result = subprocess.run(
            [sys.executable, '-c', 'import weasyprint; print("ok")'],
            capture_output=True, text=True, timeout=15,
        )
        _WEASYPRINT_OK = (result.returncode == 0 and 'ok' in result.stdout)
    except Exception:
        _WEASYPRINT_OK = False

    if not _WEASYPRINT_OK:
        print("[PDF] WeasyPrint no disponible — usando ReportLab.")
    return _WEASYPRINT_OK


def _configure_native_libraries():
    """Hace visibles a Python las DLL requeridas por WeasyPrint (Pango, GLib, Cairo, etc.) en Windows."""
    global _NATIVE_DLL_HANDLES, _NATIVE_DLL_DIRECTORIES
    if os.name != 'nt':
        return

    # Buscar directorios que contengan las DLLs de Pango/Cairo/GLib
    project_root = Path(__file__).resolve().parents[1]
    candidate_dirs = [
        # 1. MSYS2 en el sistema local
        Path('C:/msys64/ucrt64/bin'),
        Path('C:/msys64/mingw64/bin'),
        Path('C:/msys64/clang64/bin'),
        # 2. Bundle local .native dentro del proyecto
        project_root / '.native' / 'msys64' / 'ucrt64' / 'bin',
        project_root / '.native' / 'msys64' / 'mingw64' / 'bin',
        project_root / '.native' / 'bin',
        # 3. Instaladores estándar de GTK3 para Windows
        Path('C:/Program Files/GTK3-Runtime Win64/bin'),
        Path('C:/Program Files (x86)/GTK3-Runtime Win64/bin'),
    ]

    # 4. Variables de entorno personalizadas si están definidas
    custom_dir = os.environ.get('WEASYPRINT_DLL_DIRECTORIES') or os.environ.get('GTK_BASEPATH')
    if custom_dir:
        custom_dirs = []
        for d in custom_dir.split(os.pathsep):
            if d.strip():
                custom_path = Path(d.strip())
                custom_dirs.extend([custom_path, custom_path / 'bin'])
        candidate_dirs = custom_dirs + candidate_dirs

    pango_dll_dir = None
    for candidate in candidate_dirs:
        if candidate.exists() and candidate.is_dir() and any(candidate.glob('*pango*.dll')):
            pango_dll_dir = candidate.resolve()
            break

    if pango_dll_dir is None:
        print(
            "[WeasyPrint] Advertencia: no se encontraron DLL de Pango. "
            "En Windows instala Pango con MSYS2 UCRT64 y configura "
            "WEASYPRINT_DLL_DIRECTORIES=C:\\msys64\\ucrt64\\bin. "
            "Se usará ReportLab como generador de PDF alternativo."
        )
        return

    candidate_str = str(pango_dll_dir)
    normalized_path = os.path.normcase(candidate_str)
    current_path = os.environ.get('PATH', '')
    path_entries = {
        os.path.normcase(os.path.abspath(entry.strip('"')))
        for entry in current_path.split(os.pathsep)
        if entry
    }
    if normalized_path not in path_entries:
        os.environ['PATH'] = candidate_str + os.pathsep + current_path

    if normalized_path not in _NATIVE_DLL_DIRECTORIES and hasattr(os, 'add_dll_directory'):
        try:
            handle = os.add_dll_directory(candidate_str)
            _NATIVE_DLL_HANDLES.append(handle)
            _NATIVE_DLL_DIRECTORIES.add(normalized_path)
        except OSError as error:
            print(f"[WeasyPrint] No se pudo registrar directorio de DLL: {candidate_str} — {error}")

    # Generar un fonts.conf limpio y aislado para evitar los avisos de sintaxis en conf.d de MSYS2 (xsi:nil, etc.)
    try:
        import tempfile
        fonts_cache_dir = Path(tempfile.gettempdir()) / 'autodocs_fc_cache'
        fonts_cache_dir.mkdir(parents=True, exist_ok=True)
        clean_conf_path = Path(tempfile.gettempdir()) / 'autodocs_fonts.conf'

        font_dirs = ['C:\\Windows\\Fonts', 'C:\\Windows\\System32\\Fonts']
        for cand in candidate_dirs:
            try:
                msys_share_fonts = cand.parent / 'share' / 'fonts'
                if msys_share_fonts.exists():
                    font_dirs.append(str(msys_share_fonts.resolve()))
            except Exception:
                pass

        dirs_xml = '\n'.join(f'    <dir>{d}</dir>' for d in font_dirs if Path(d).exists())
        clean_xml = f"""<?xml version="1.0"?>
<!DOCTYPE fontconfig SYSTEM "urn:fontconfig:fonts.dtd">
<fontconfig>
{dirs_xml}
    <cachedir>{fonts_cache_dir}</cachedir>
    <config>
        <rescan><int>3600</int></rescan>
    </config>
</fontconfig>
"""
        clean_conf_path.write_text(clean_xml, encoding='utf-8')
        os.environ['FONTCONFIG_FILE'] = str(clean_conf_path.resolve())
        os.environ['FONTCONFIG_PATH'] = str(clean_conf_path.parent.resolve())
    except Exception:
        pass


class DocumentExporter:
    def __init__(self, project: dict, analysis_result: dict, lang: str = None):
        self.project = project
        self.results = analysis_result.get('results', {})
        self.docs    = analysis_result.get('documentation', {})
        raw_lang = lang or project.get('doc_language') or project.get('language_code') or project.get('preferred_language') or 'es'
        raw_lang = str(raw_lang).lower()
        self.lang = 'en' if raw_lang.startswith('en') else 'es'
        EXPORT_BASE.mkdir(parents=True, exist_ok=True)

    def t(self, key):
        return _export_t(self.lang, key)

    def _score_label(self, score):
        if score >= 80:
            return self.t('excellent')
        if score >= 60:
            return self.t('acceptable')
        return self.t('needs_improvement')

    def to_markdown(self) -> str:
        return self.docs.get('full_markdown', self.t('no_docs'))

    def _markdown_table_to_html(self, text: str) -> str:
        lines = text.split('\n')
        output = []
        i = 0
        while i < len(lines):
            line = lines[i]
            if '|' in line and i + 1 < len(lines):
                sep_line = lines[i + 1]
                if _SEP_RE.match(sep_line):
                    headers = [cell.strip() for cell in re.split(r'\s*\|\s*', line.strip().strip('|'))]
                    rows = []
                    i += 2
                    while i < len(lines) and '|' in lines[i] and lines[i].strip():
                        row_cells = [cell.strip() for cell in re.split(r'\s*\|\s*', lines[i].strip().strip('|'))]
                        if len(row_cells) == len(headers):
                            rows.append(row_cells)
                        i += 1
                    head_html = ''.join(f'<th>{h}</th>' for h in headers)
                    body_html = ''.join('<tr>' + ''.join(f'<td>{c}</td>' for c in row) + '</tr>' for row in rows)
                    output.append(f'<table class="report-table"><thead><tr>{head_html}</tr></thead><tbody>{body_html}</tbody></table>')
                    continue
            output.append(line)
            i += 1
        return '\n'.join(output)

    def _render_markdown_with_node(self, md: str) -> str:
        script_path = Path(__file__).resolve().parents[1] / 'markdown_to_html.js'
        if script_path.exists() is not True:
            raise FileNotFoundError('Node markdown script not found')
        result = subprocess.run(
            ['node', str(script_path)],
            input=md,
            text=True,
            capture_output=True,
            cwd=script_path.parent,
            timeout=30
        )
        if result.returncode != 0:
            raise RuntimeError(f"Node markdown conversion failed: {result.stderr.strip()}")
        return result.stdout

    @staticmethod
    def _parse_code_fragment(markup: str) -> tuple[str, str, str, str]:
        title_match = re.search(r'<div class="frag-title">(.*?)</div>', markup, re.DOTALL)
        file_match = re.search(r'<div class="frag-file">(.*?)</div>', markup, re.DOTALL)
        code_match = re.search(r'<pre><code>(.*?)</code></pre>', markup, re.DOTALL)
        explanation_match = re.search(
            r'<div class="code-explanation">(.*?)</div>', markup, re.DOTALL
        )

        title = _html.unescape(title_match.group(1).strip()) if title_match else ''
        file_path = _html.unescape(file_match.group(1).strip()) if file_match else ''
        code = _html.unescape(code_match.group(1)) if code_match else ''
        explanation = explanation_match.group(1) if explanation_match else ''
        explanation = re.sub(r'<br\s*/?>', ' ', explanation, flags=re.IGNORECASE)
        explanation = re.sub(r'<strong[^>]*>', '**', explanation, flags=re.IGNORECASE)
        explanation = re.sub(r'</strong>', '**', explanation, flags=re.IGNORECASE)
        explanation = re.sub(r'<code[^>]*>', '`', explanation, flags=re.IGNORECASE)
        explanation = re.sub(r'</code>', '`', explanation, flags=re.IGNORECASE)
        explanation = re.sub(r'<[^>]+>', '', explanation)
        explanation = _html.unescape(explanation).strip()
        return title, file_path, code, explanation

    # ─────────────────────────────────────────────────────────────────────────
    # Tablas anchas → página horizontal (solo esa página)
    # ─────────────────────────────────────────────────────────────────────────
    def _is_wide_table(self, table_html: str) -> bool:
        """Estima si una tabla HTML cabe en una página A4 vertical."""
        grid = []
        for row in _ROW_RE.findall(table_html):
            cells = _CELL_RE.findall(row)
            texts = [re.sub(r'\s+', ' ', _html.unescape(_TAG_RE.sub('', c))).strip() for c in cells]
            if texts:
                grid.append(texts)
        if not grid:
            return False

        n_cols = max(len(r) for r in grid)
        if n_cols >= LANDSCAPE_MIN_COLS:
            return True

        min_total = 0.0   # ancho mínimo (palabra más larga de cada columna)
        nat_total = 0.0   # ancho "natural" (texto más largo, con tope)
        for c in range(n_cols):
            longest_token = 0
            longest_text = 0
            for r in grid:
                if c < len(r):
                    text = r[c]
                    longest_text = max(longest_text, len(text))
                    for tok in text.split():
                        longest_token = max(longest_token, len(tok))
            min_total += longest_token * CHAR_PX + CELL_PAD_PX
            nat_total += min(longest_text, NATURAL_CAP_CHARS) * CHAR_PX + CELL_PAD_PX

        return (min_total > PORTRAIT_WIDTH_PX
                or nat_total > PORTRAIT_WIDTH_PX * NATURAL_OVERFLOW_RATIO)

    def _wrap_wide_tables(self, html_body: str) -> str:
        """
        Envuelve cada tabla ancha en <div class="table-landscape">.
        La regla CSS `page: landscape` hace que solo esa página sea horizontal;
        el contenido anterior y posterior vuelve a orientación vertical.
        """
        out = []
        pos = 0
        for m in _TABLE_RE.finditer(html_body):
            table_html = m.group(0)
            if not self._is_wide_table(table_html):
                continue
            start, end = m.span()
            before = html_body[pos:start]
            lead = _LEAD_RE.search(before)
            if lead:
                out.append(before[:lead.start()])
                intro = before[lead.start():]
            else:
                out.append(before)
                intro = ''
            out.append(f'<div class="table-landscape">{intro}{table_html}</div>')
            pos = end
        out.append(html_body[pos:])
        return ''.join(out)

    def _wrap_table_titles(self, html_body: str) -> str:
        """
        Wraps each heading immediately followed by a narrow table in a
        break-inside:avoid div so the title never ends up orphaned on its own
        page without the table.
        Wide (landscape) tables are already handled by _wrap_wide_tables.
        """
        # Match: heading tag + optional paragraph + non-landscape table
        _HEADING_TABLE_RE = re.compile(
            r'(<h[1-6]\b[^>]*>(?:(?!</h[1-6]>).)*</h[1-6]>)'
            r'(\s*(?:<p\b[^>]*>(?:(?!</p>).)*</p>\s*)?)'
            r'(<table\b(?![^>]*table-landscape)[^>]*>.*?</table>)',
            re.DOTALL | re.IGNORECASE,
        )

        def wrap(m):
            # Only wrap if the table is not already inside a landscape div
            return (
                '<div style="break-inside:avoid;page-break-inside:avoid;">'
                f'{m.group(1)}{m.group(2)}{m.group(3)}'
                '</div>'
            )

        return _HEADING_TABLE_RE.sub(wrap, html_body)

    def _wrap_diagram_sections(self, html_body: str) -> str:
        """Agrupa cada diagrama con su título y descripción para WeasyPrint."""
        pattern = re.compile(
            r'(<h3\b[^>]*>(?:.*?<span[^>]*>.*?</span>\s*)?.*?(?:Diagrama|Diagram).*?</h3>)'
            r'(.*?)(?=<h[123]\b[^>]*>|<hr\b[^>]*>|$)',
            flags=re.DOTALL | re.IGNORECASE,
        )

        def wrap(match):
            heading = match.group(1)
            content = match.group(2)
            if re.search(r'<img\b', content, flags=re.IGNORECASE):
                return (
                    '<div class="diagram-section">'
                    f'{heading}{content}'
                    '</div>'
                )
            return match.group(0)

        return pattern.sub(wrap, html_body)

    def _to_html_legacy(self) -> str:
        md = self.to_markdown()
        project_name = self.project.get('name', self.t('project_fallback'))

        try:
            html_body = self._render_markdown_with_node(md)
        except Exception:
            try:
                from markdown import markdown as markdown_to_html
                html_body = markdown_to_html(md, extensions=['fenced_code', 'tables', 'attr_list', 'sane_lists', 'extra'])
            except Exception:
                html_body = md
                # Las tablas se convierten primero para que el reemplazo de '---' no rompa sus separadores
                html_body = self._markdown_table_to_html(html_body)
                html_body = re.sub(r'^#### (.+)$', r'<h4>\1</h4>', html_body, flags=re.MULTILINE)
                html_body = re.sub(r'^### (.+)$',  r'<h3>\1</h3>', html_body, flags=re.MULTILINE)
                html_body = re.sub(r'^## (.+)$',   r'<h2>\1</h2>', html_body, flags=re.MULTILINE)
                html_body = re.sub(r'^# (.+)$',    r'<h1>\1</h1>', html_body, flags=re.MULTILINE)
                html_body = re.sub(r'\*\*(.+?)\*\*', r'<strong>\1</strong>', html_body)
                html_body = re.sub(r'\*(.+?)\*',      r'<em>\1</em>',        html_body)
                html_body = re.sub(r'`([^`]+)`', r'<code>\1</code>', html_body)
                html_body = re.sub(r'```[\w]*\n(.*?)```', r'<pre><code>\1</code></pre>', html_body, flags=re.DOTALL)
                html_body = re.sub(r'^---$', '<hr>', html_body, flags=re.MULTILINE)

        # Todas las tablas comparten el mismo diseño (el de «Stack Tecnológico»)
        html_body = re.sub(r'<table(?![^>]*class=)', '<table class="report-table"', html_body)

        # Inject section IDs onto h1/h2/h3 headings
        sec_counter = [0]
        toc_headings = []
        def inject_section_id(m):
            sec_counter[0] += 1
            tag = m.group(1)
            text = m.group(2)
            level = int(tag[1])
